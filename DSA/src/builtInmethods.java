import java.util.Arrays;


public class builtInmethods {
    public static void main(String[] args) {

        int [] array={20,30,6,2,34,56,78,99};

        //for each loop
        for(int ele:array){
            System.out.println(ele+ "");

        }

        Arrays.sort(array);

        for (int i = 0; i <array[i] ; i++) {
            System.out.println(array[i]);

        }


    }
}
